#!/bin/bash
# Builds the ready-to-run hosting bundle (run in CI after `npm ci && npm run build`).
# The server needs neither npm nor the Prisma CLI: API/worker/ops are bundled with esbuild,
# only the argon2 native module ships as a package (D-020).
# Usage: scripts/build-release.sh [output-dir] [version-label]
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="${1:-release}"
LABEL="${2:-$(git rev-parse --short HEAD 2>/dev/null || echo local)}"
[ -f apps/api/dist/server.js ] || { echo "Run 'npm run build' first" >&2; exit 1; }
[ -f apps/web/out/index.html ] || { echo "Web build missing (apps/web/out)" >&2; exit 1; }

rm -rf "$OUT"
mkdir -p "$OUT/apps/api/dist" "$OUT/apps/api/prisma" "$OUT/apps/api/node_modules/@node-rs" "$OUT/apps/web" "$OUT/deploy"

npx esbuild apps/api/dist/server.js apps/api/dist/worker.js apps/api/dist/ops.js \
  --bundle --platform=node --target=node20 --format=cjs --legal-comments=none \
  --external:@node-rs/argon2 --log-level=warning --outdir="$OUT/apps/api/dist"

cp -r apps/api/prisma/migrations "$OUT/apps/api/prisma/"
cp -r apps/web/out "$OUT/apps/web/out"
cp -rL node_modules/@node-rs/argon2 node_modules/@node-rs/argon2-linux-x64-gnu "$OUT/apps/api/node_modules/@node-rs/"
cp deploy/cpanel/*.sh deploy/cpanel/new-env.js "$OUT/deploy/"
cp deploy/cpanel/.cpanel.yml "$OUT/.cpanel.yml"
chmod +x "$OUT"/deploy/*.sh

cat > "$OUT/package.json" <<JSON
{
  "name": "ai-sales-hq-release",
  "private": true,
  "description": "Unutilmas Ta'm AI Sales HQ - ready-to-run bundle for cPanel (do not run npm install)",
  "engines": { "node": ">=20.19" }
}
JSON
printf '%s\nbuilt %s\n' "$LABEL" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" > "$OUT/VERSION"
cat > "$OUT/README.md" <<'MD'
# AI Sales HQ — release bundle

Generated by GitHub Actions from `main` (`ai-sales-hq/`). Do not edit; do not run `npm install`.
Installation and updates: `ai-sales-hq/docs/DEPLOY_UZ.md` on the `main` branch.
MD
echo "Release bundle: $OUT ($(du -sh "$OUT" | cut -f1)), version $LABEL"
